#!/usr/bin/env python3
"""Generate firmware/src/secrets.h from the repo-root .env.

    ./scripts/gen-secrets.py dad
    ./scripts/gen-secrets.py emma --out /tmp/secrets.h

Run this on the machine that flashes the board. The generated header is
gitignored; .env stays the single source of truth for WiFi credentials, the
Worker URL, and the per-device bearer token.

Since 0.2.0 the relay is a Cloudflare Worker + Durable Object, so the
generated header carries MORSE_SERVER_URL (a full https:// URL, no port)
as SERVER_URL — not the old LAN RELAY_HOST / RELAY_PORT. A stale .env
that still sets RELAY_HOST is refused loudly instead of flashing the
dead LAN address onto a board.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ENV = REPO_ROOT / ".env"
DEFAULT_OUT = REPO_ROOT / "firmware" / "src" / "secrets.h"
DEVICE_RE = re.compile(r"^[a-z][a-z0-9_-]{0,31}$")
PLACEHOLDER = "REPLACE_WITH_openssl_rand_hex_24"
MIN_TOKEN_LEN = 16


class EnvError(RuntimeError):
    pass


def parse_env(path: Path) -> dict[str, str]:
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise EnvError(
            f"{path} not found; copy .env.example to .env and fill it in"
        ) from exc

    values: dict[str, str] = {}
    for lineno, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].lstrip()
        key, sep, value = line.partition("=")
        if not sep:
            raise EnvError(f"{path}:{lineno}: expected KEY=VALUE")
        key = key.strip()
        value = value.strip()

        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            quote = value[0]
            value = value[1:-1]
            if quote == '"':
                value = (
                    value.replace("\\n", "\n")
                    .replace("\\t", "\t")
                    .replace('\\"', '"')
                    .replace("\\\\", "\\")
                )
        values[key] = value
    return values


def c_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    escaped = escaped.replace("\n", "\\n").replace("\t", "\\t")
    return f'"{escaped}"'


def require(values: dict[str, str], key: str) -> str:
    value = values.get(key, "").strip()
    if not value:
        raise EnvError(f"missing {key} in .env")
    return value


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("device", help="device id (dad, emma)")
    parser.add_argument("--env", type=Path, default=Path(os.environ.get("MORSE_ENV_FILE", DEFAULT_ENV)))
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--force", action="store_true", help="overwrite an existing secrets.h")
    args = parser.parse_args()

    device = args.device.strip().lower()
    if not DEVICE_RE.match(device):
        raise EnvError(f"invalid device id {device!r}")

    out = args.out.expanduser().resolve()
    if out.exists() and not args.force:
        raise EnvError(f"{out} already exists; pass --force to overwrite")

    values = parse_env(args.env.expanduser().resolve())

    if values.get("RELAY_HOST") or values.get("RELAY_PORT"):
        raise EnvError(
            "stale .env: RELAY_HOST/RELAY_PORT were removed in 0.2.0 when the "
            "laptop relay was replaced by the Cloudflare Worker. Delete those "
            "lines and set MORSE_SERVER_URL instead "
            "(e.g. https://morse.gulfrenderstudio.com, or "
            "http://localhost:8787 for local dev)"
        )

    ssid = require(values, "WIFI_SSID")
    password = require(values, "WIFI_PASS")
    server_url = require(values, "MORSE_SERVER_URL")
    token_key = f"MORSE_TOKEN_{device.upper().replace('-', '_')}"
    token = require(values, token_key)

    if ssid.startswith("your-wifi") or password.startswith("your-wifi"):
        raise EnvError("edit WIFI_SSID and WIFI_PASS in .env before flashing")
    if token == PLACEHOLDER or token.upper().startswith("REPLACE"):
        raise EnvError(f"replace the placeholder {token_key} in .env")
    if len(token) < MIN_TOKEN_LEN:
        raise EnvError(f"{token_key} must be at least {MIN_TOKEN_LEN} characters")
    if not server_url.startswith(("https://", "http://")):
        raise EnvError(
            f"MORSE_SERVER_URL must be a full URL, got {server_url!r} "
            "(e.g. https://morse.gulfrenderstudio.com)"
        )
    server_url = server_url.rstrip("/")

    header = f"""// Generated by scripts/gen-secrets.py from .env - do not edit or commit.
// Regenerate with: ./scripts/gen-secrets.py {device} --force
#pragma once

#define WIFI_SSID    {c_string(ssid)}
#define WIFI_PASS    {c_string(password)}

#define SERVER_URL   {c_string(server_url)}

#define DEVICE_ID    {c_string(device)}
#define DEVICE_NAME  {c_string(device.upper())}
#define DEVICE_TOKEN {c_string(token)}
"""

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header, encoding="utf-8")
    try:
        out.chmod(0o600)
    except OSError:
        pass

    print(f"wrote {out} for device {device!r} ({server_url})")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except EnvError as exc:
        print(f"error: {exc}", file=sys.stderr)
        raise SystemExit(1)
